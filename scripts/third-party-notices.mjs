import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--locked", "--format-version", "1", "--filter-platform", "wasm32-unknown-unknown", "--features", "webgpu,threads"], { cwd: root, encoding: "utf8", maxBuffer: 32_000_000 }));
const resolved = new Set(metadata.resolve.nodes.map(node => node.id));
const packages = metadata.packages.filter(pkg => pkg.source && resolved.has(pkg.id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const lines = ["# Third-party notices", "", "Generated by `node scripts/third-party-notices.mjs` from Cargo.lock for the wasm32 build with `webgpu,threads`. This includes transitive dependencies and host build tools; it is a superset of shipped wasm code. SimRep itself uses the separate root LICENSE. Dependency license expressions are package metadata, not relicensing by this project.", "", "Each linked directory contains the upstream license/notice files shipped in that exact registry package. Keep these files with redistributed packages. Regenerate after changing Cargo.lock. A package without a standalone notice file is identified explicitly below; its SPDX expression and upstream repository remain recorded.", "", "| Package | License expression | Upstream | License/notice files |", "| --- | --- | --- | --- |"];
for (const pkg of packages) {
  const directory = path.dirname(pkg.manifest_path);
  const names = (await readdir(directory)).filter(name => /^(licen[cs]e|copying|notice|copyright)([._-]|$)/i.test(name));
  const links = [];
  for (const name of names) {
    const source = path.join(directory, name);
    let bytes;
    try { bytes = await readFile(source); } catch (error) { if (error.code === "EISDIR") continue; throw error; }
    const relative = `THIRD_PARTY_LICENSES/${pkg.name}-${pkg.version}/${name}`;
    await mkdir(path.dirname(path.join(root, relative)), { recursive: true });
    await writeFile(path.join(root, relative), bytes);
    links.push(`[${name}](${relative})`);
  }
  lines.push(`| ${pkg.name} ${pkg.version} | ${pkg.license ?? "See upstream"} | ${pkg.repository ? `[source](${pkg.repository})` : "Registry source"} | ${links.join(", ") || "No standalone license file in registry archive"} |`);
}
await writeFile(path.join(root, "THIRD_PARTY_NOTICES.md"), `${lines.join("\n")}\n`);
console.log(`Recorded ${packages.length} dependency packages with upstream license files.`);
